def write_mcp(wave: str, subdir: str, mcp_name: str, description: str, category: str, tools: list, tags: list, icon: str, domain_label: str = ""):
    """Write a server.py and manifest.json for an MCP.
    `subdir` is the directory name; mcp_name is the registered tool name.
    """
    base = SERVERS / wave / subdir
    base.mkdir(parents=True, exist_ok=True)
    # server.py
    server_py = render_server(subdir, mcp_name, description, category, tools, tags, icon)
    (base / "server.py").write_text(server_py)
    # manifest.json
    m = build_manifest(
        f"mcp-{mcp_name}",
        displayName=description,
        version="1.0.0",
        description=description,
        category=category,
        tools=[{"name": t[0], "description": t[1]} for t in tools],
        tags=tags,
        iconEmoji=icon,
        author={"agentId": "@nexus-genesis", "displayName": "Nexus Genesis", "verified": True},
    )
    m.mcp["command"] = f"python -m servers.{wave}.{subdir}.server"
    m.write(base / "manifest.json")


