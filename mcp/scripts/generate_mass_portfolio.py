TOOL_RETURN_TEMPLATES = {
    "list_items": 'return {{"ok": True, "items": [], "count": 0, "domain": DOMAIN}}',
    "get_item": 'return {{"ok": True, "id": item_id, "domain": DOMAIN, "data": {{}}}}',
    "create_item": 'return {{"ok": True, "id": "new-{int(time.time())}", "domain": DOMAIN, "data": data}}',
    "update_item": 'return {{"ok": True, "id": item_id, "domain": DOMAIN, "updated": True}}',
    "delete_item": 'return {{"ok": True, "id": item_id, "domain": DOMAIN, "deleted": True}}',
    "search_items": 'return {{"ok": True, "query": q, "domain": DOMAIN, "results": []}}',
    "get_stats": 'return {{"ok": True, "domain": DOMAIN, "total": 0, "by_status": {{}}}}',
    "export_items": 'return {{"ok": True, "domain": DOMAIN, "format": fmt, "size": 0}}',
    "import_items": 'return {{"ok": True, "domain": DOMAIN, "imported": 0}}',
    "validate_item": 'return {{"ok": True, "domain": DOMAIN, "valid": True, "errors": []}}',
}


def render_server(domain: str, mcp_name: str, description: str, category: str, tools: list, tags: list, icon: str) -> str:
    """Render a complete server.py for a given MCP."""
    domain_upper = domain.upper()
    # Build tool registrations
    tool_lines = []
    for tool_name, tool_desc in tools:
        # Find the matching template
        kind = None
        for k, (n, d) in COMMON_TOOLS.items():
            if n == tool_name:
                kind = k
                break
        ret_template = TOOL_RETURN_TEMPLATES.get(tool_name, 'return {"ok": True, "domain": DOMAIN}')
        # Build the @server.tool decorator block
        sig_args = ""
        if tool_name == "list_items":
            sig_args = "limit: int = 20, offset: int = 0"
        elif tool_name == "get_item":
            sig_args = "item_id: str"
        elif tool_name == "create_item":
            sig_args = "data: dict"
        elif tool_name == "update_item":
            sig_args = "item_id: str, data: dict"
        elif tool_name == "delete_item":
            sig_args = "item_id: str"
        elif tool_name == "search_items":
            sig_args = "q: str"
        elif tool_name == "get_stats":
            sig_args = ""
        elif tool_name == "export_items":
            sig_args = "fmt: str = 'json'"
        elif tool_name == "import_items":
            sig_args = "source: str"
        elif tool_name == "validate_item":
            sig_args = "item_id: str"
        tool_lines.append(f'''@server.tool(description="{tool_desc}")
def {tool_name}({sig_args}) -> dict:
    return {ret_template.replace("DOMAIN", f'"{domain_upper}"')}
''')

    tools_block = "\n".join(tool_lines)
    server = f'''r"""
mcp-{mcp_name} — {description}.

Auto-generated by generate_mass_portfolio.py (Wave 3, domain={domain}).
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from mcp_sdk import Server


DOMAIN = "{domain}"
server = Server(name="mcp-{mcp_name}", version="1.0.0", title="{description}", description="{description}")


{tools_block}
if __name__ == "__main__":
    server.run()
'''
    return server


